"""Screen vision by voice: "что у меня на экране", "прочитай что тут написано", "объясни ошибку на экране",
"переведи текст на экране". Looks at the active window only when asked (see vision.py)."""

import core
from core import Ctx, skill


@skill(
    "vision.look",
    title={"ru": "Посмотреть на экран: прочитать, объяснить ошибку, перевести"},
    patterns={"ru": [
        r"(?:что|чё|че) (?:у меня |там |сейчас )?(?:на|с) (?:экране|экраном|мониторе)",
        r"посмотри (?:на )?(?:экран|монитор|сюда|на это|что (?:тут|здесь|там))",
        r"(?:что|кто) (?:тут|здесь) (?:написано|изображено|нарисовано|показано|за ошибка)",
        r"(?:прочитай|прочти|зачитай)(?: что| мне)? (?:тут|здесь|с экрана|на экране|текст на экране|это окно)",
        r"\b(?:на экране|на мониторе|в этом окне)\b",
        r"(?:объясни|переведи|разбери|помоги с) (?:эту |этот |это |мне )?(?:ошибку|текст|окно|страницу|картинку)(?: на экране| тут| здесь)?$",
    ]},
    examples={"ru": ["Что у меня на экране?", "Объясни ошибку на экране", "Переведи текст на экране"]},
    priority=9,
)
def look(ctx: Ctx) -> str:
    import vision
    if ctx.source == "голос" and core.feature("voice_replies"):
        core.emit({"type": "status", "state": "thinking"})
    return vision.look(ctx.text)
